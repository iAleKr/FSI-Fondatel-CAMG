    //metodo que combina los dos filtros sin que se sobreescriban
    private void filtrar() {
        if (CBTurno.getSelectedItem() == null || CBEstado.getSelectedItem() == null) {
            return;
        }

        String tur = CBTurno.getSelectedItem().toString();
        String est = CBEstado.getSelectedItem().toString();

        if (tur.equals("Todos") && est.equals("Todos")) {
            cnx.entablar(todo, TCajeros);
        } else if (!tur.equals("Todos") && est.equals("Todos")) {
            cnx.entablar(String.format(por_turno, tur), TCajeros);
        } else if (tur.equals("Todos") && !est.equals("Todos")) {
            cnx.entablar(String.format(por_estado, est), TCajeros);
        } else {
            cnx.entablar(String.format(por_ambos, tur, est), TCajeros);
        }

    }

