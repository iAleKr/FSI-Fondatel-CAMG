    // Método que combina ambos filtros sin que se sobreescriban
    private void filtrar() {
        if (CBTipo.getSelectedItem() == null || CBCliente.getSelectedItem() == null) {
            return;
        }

        String tip = CBTipo.getSelectedItem().toString();
        String cli = CBCliente.getSelectedItem().toString();

        if (tip.equals("Todos") && cli.equals("Todos")) {
            cnx.entablar(todo, TClientes);
        } else if (!tip.equals("Todos") && cli.equals("Todos")) {
            cnx.entablar(String.format(por_tipo, tip), TClientes);
        } else if (tip.equals("Todos") && !cli.equals("Todos")) {
            cnx.entablar(String.format(por_cliente, cli), TClientes);
        } else {
            cnx.entablar(String.format(por_ambos, tip, cli), TClientes);
        }

    }

