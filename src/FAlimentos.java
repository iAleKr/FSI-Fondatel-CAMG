    private void BAbrirFotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BAbrirFotoActionPerformed
        // TODO add your handling code here:
        JFileChooser fc = new JFileChooser();
        int respuesta = fc.showOpenDialog(this);
        
        if (respuesta == JFileChooser.APPROVE_OPTION) {
            //cargar la foto que fue seleccionada
            foto = new ImageIcon(fc.getSelectedFile().getAbsolutePath());

            //ajustar la foto al tamaño exacto del JLabel
            Image imgEscalada = cnx.escalarImagen(foto.getImage(), LFoto.getWidth(), LFoto.getHeight());
            LFoto.setIcon(new ImageIcon(imgEscalada));
            
        }

    }//GEN-LAST:event_BAbrirFotoActionPerformed

    private void BRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegistrarActionPerformed
        
        String id = txtID.getText();
        String nom = txtNombre.getText();
        String desc = txtDescripcion.getText();
        String pre = txtPrecio.getText();
        String cat = CBCategoria.getSelectedItem().toString();
        String est = CBEstado.getSelectedItem().toString();
        ImageIcon car = foto;
        
        Alimento aa = new Alimento(id, nom, desc, pre, cat, est, car, cnx);
        
        if (aa.insertar(cnx) == 1) {
            cnx.entablar("SELECT * FROM alimentos", TAlimentos, 8, 20, 30, 10, 16, 12, 12);
            
            txtID.setText("");
            txtNombre.setText("");
            txtDescripcion.setText("");
            txtPrecio.setText("");
            
            CBCategoria.setSelectedIndex(0);
            CBEstado.setSelectedIndex(0);
            
            LFoto.setIcon(null);
            foto = null;
            
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar el alimento");
        }
        

    }//GEN-LAST:event_BRegistrarActionPerformed

    private void TAlimentosMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TAlimentosMousePressed
        // TODO add your handling code here:

        int ren = TAlimentos.getSelectedRow();
        DefaultTableModel modelo = (DefaultTableModel) TAlimentos.getModel();
        
        if (ren >= 0) {
            txtID.setText(modelo.getValueAt(ren, 0).toString());
            txtNombre.setText(modelo.getValueAt(ren, 1).toString());
            txtDescripcion.setText(modelo.getValueAt(ren, 2).toString());
            txtPrecio.setText(modelo.getValueAt(ren, 3).toString());
            CBCategoria.setSelectedItem(modelo.getValueAt(ren, 4).toString());
            CBEstado.setSelectedItem(modelo.getValueAt(ren, 5).toString());
            
            foto = new ImageIcon(cnx.escalarImagen(((ImageIcon) modelo.getValueAt(ren, 6)).
                    getImage(), 194, 235));
            
            LFoto.setIcon(foto);
            
        }
    }//GEN-LAST:event_TAlimentosMousePressed

