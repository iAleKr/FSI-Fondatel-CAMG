    private void CBPuestoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CBPuestoActionPerformed
        // TODO add your handling code here:

        if (CBPuesto.getSelectedItem() != null) {
            String p = CBPuesto.getSelectedItem().toString();
            if (p.equals("Todos")) {
                cnx.entablar(empleados, TDatos);
            } else {
                cnx.entablar(String.format(por_puesto, p), TDatos);
            }
       }
 
    }//GEN-LAST:event_CBPuestoActionPerformed

